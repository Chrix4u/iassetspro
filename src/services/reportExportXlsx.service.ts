// ============================================================================
// TYPES
// ============================================================================

/** Column definition for a data sheet — drives header labels, widths, formatting */
export interface ReportColumn {
  key: string;
  header: string;
  width?: number; // character width, default 15
  format?: 'date' | 'datetime' | 'number' | 'currency' | 'percentage' | 'text';
}

/** Options for creating a standard workbook */
export interface CreateWorkbookOptions {
  /** Report title shown on the Summary sheet */
  reportName: string;
  /** Human-readable description */
  description?: string;
  /** Plant / site name (from plant table or user selection) */
  plantName?: string;
  /** Plant ID (for reference) */
  plantId?: string;
  /** Active filter values applied to the report */
  filters?: Record<string, string | undefined>;
  /** Name / email of the user generating the report */
  generatedBy: string;
  /** KPI metrics shown on the Summary sheet */
  kpis?: Array<{ label: string; value: string | number }>;
  /** Company name (defaults to 'iAssetsPro EAM') */
  companyName?: string;
}

/** Options passed when adding a data sheet */
export interface AddDataSheetOptions {
  /** Freeze the top row + N left columns? Default true */
  freezeHeader?: boolean;
  /** Number of left columns to freeze (default 0) */
  freezeColumns?: number;
  /** Enable auto-filter on headers? Default true */
  autoFilter?: boolean;
  /** Stripe alternating row colours (light grey / white). Default true */
  stripeRows?: boolean;
  /** Default column width when not specified in ReportColumn */
  defaultWidth?: number;
}

/** A single row for analytics — keys map to column headers */
export type AnalyticsRow = Record<string, string | number | boolean | null | undefined>;

/** Options for analytics sheet */
export interface AddAnalyticsOptions {
  /** Enable auto-filter */
  autoFilter?: boolean;
}

