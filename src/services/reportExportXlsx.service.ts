/**
 * Write the workbook to a Buffer suitable for NextResponse.
 */
export function generateXlsxBuffer(workbook: XLSX.WorkBook): Buffer {
  const buffer = XLSX.write(workbook, {
    type: 'buffer',
    bookType: 'xlsx',
    cellStyles: true,
  });
  return Buffer.from(buffer);
}

// ============================================================================
// INTERNAL HELPERS
// ============================================================================

/** Apply column-level format to a raw value for the AOA grid. */
function applyCellFormat(
  raw: unknown,
  format?: ReportColumn['format'],
): string | number {
  switch (format) {
    case 'date':
      return formatDate(raw);
    case 'datetime':
      if (raw == null || raw === '') return '';
      const d = raw instanceof Date ? raw : new Date(String(raw));
      if (isNaN(d.getTime())) return String(raw);
      return XLSX.SSF.format('yyyy-mm-dd hh:mm:ss', d);
    case 'number':
      return formatNumber(raw);
    case 'currency':
      return formatCurrency(raw);
    case 'percentage':
      return formatPercentage(raw);
    case 'text':
    default:
      if (raw == null) return '';
      return String(raw);
  }
}

// ============================================================================
// SAFE FILENAME HELPER
// ============================================================================

/**
 * Convert a report name into a safe filename component.
 */
export function safeFilename(reportName: string): string {
  return reportName
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/(^_|_$)/g, '');
}

/**
 * Build a full filename with date stamp.
 */
export function buildFilename(reportName: string, ext: string = 'xlsx'): string {
  const date = new Date().toISOString().split('T')[0];
  return `${safeFilename(reportName)}_${date}.${ext}`;
}
