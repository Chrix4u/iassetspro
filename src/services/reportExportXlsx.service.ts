// HELPERS — cell-level formatting
// ============================================================================

/**
 * Format a Date (or date string) as `YYYY-MM-DD`.
 * Passes through null/undefined/empty strings unchanged.
 */
export function formatDate(val: unknown): string | number {
  if (val == null || val === '') return '';
  const d = val instanceof Date ? val : new Date(String(val));
  if (isNaN(d.getTime())) return String(val);
  // Return an Excel serial date number so Excel recognises it as a date
  return XLSX.SSF.parse_date_code(
    XLSX.SSF.format_date(
      'yyyy\\-mm\\-dd',
      { D: d.getDate(), T: d.getHours(), Y: d.getFullYear(), H: 0, M: d.getMonth() + 1, S: 0 },
    ),
  ) ? XLSX.SSF.format('yyyy-mm-dd', d) : String(val);
}

/**
 * Format a number with configurable decimal places.
 */
export function formatNumber(val: unknown, decimals: number = 2): string | number {
  if (val == null || val === '') return '';
  const n = Number(val);
  if (isNaN(n)) return String(val);
  return Number(n.toFixed(decimals));
}

/**
 * Format a currency value.
 */
export function formatCurrency(val: unknown): string | number {
  if (val == null || val === '') return '';
  const n = Number(val);
  if (isNaN(n)) return String(val);
  return Number(n.toFixed(2));
}

/**
 * Format a percentage value (0-100 or 0-1).
 * If the value is <= 1, it is treated as a ratio and multiplied by 100.
 */
export function formatPercentage(val: unknown): string | number {
  if (val == null || val === '') return '';
  const n = Number(val);
  if (isNaN(n)) return String(val);
  const pct = n <= 1 ? n * 100 : n;
  return `${pct.toFixed(1)}%`;
}

