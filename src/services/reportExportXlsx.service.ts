/**
 * Create a workbook pre-populated with a "Summary" sheet containing:
 * - Company / app branding
 * - Report name & description
 * - Plant & filter metadata
 * - Generated date/time
 * - Generated by
 * - KPI summary row
 *
 * Returns the XLSX.WorkBook ready for `addDataSheet` / `addAnalyticsSheet`.
 */
export function createStandardWorkbook(options: CreateWorkbookOptions): XLSX.WorkBook {
  const wb = XLSX.utils.book_new();
  const companyName = options.companyName || 'iAssetsPro EAM';
  const now = new Date();

  // Build summary rows
  const rows: Array<Array<string>> = [];

  // Branding header
  rows.push([companyName]);
  rows.push(['Asset Management']);
  rows.push([]);

  // Report metadata
  rows.push(['Report:', options.reportName]);
  if (options.description) {
    rows.push(['Description:', options.description]);
  }
  rows.push([]);

  // Plant
  rows.push(['Plant:', options.plantName || 'All Plants']);
  if (options.plantId) {
    rows.push(['Plant ID:', options.plantId]);
  }
  rows.push([]);

  // Filters
  if (options.filters && Object.keys(options.filters).length > 0) {
    rows.push(['Filters Applied:']);
    for (const [key, value] of Object.entries(options.filters)) {
      if (value !== undefined && value !== '') {
        rows.push([`  ${key}:`, String(value)]);
      }
    }
    rows.push([]);
  }

  // Timestamp
  rows.push(['Generated:', now.toISOString()]);
  rows.push(['Generated By:', options.generatedBy]);
  rows.push([]);

  // KPI summary
  if (options.kpis && options.kpis.length > 0) {
    rows.push(['KPI Summary']);
    rows.push(['Metric', 'Value']);
    for (const kpi of options.kpis) {
      rows.push([kpi.label, String(kpi.value)]);
    }
  }

  const ws = XLSX.utils.aoa_to_sheet(rows);

  // Column widths — first column 22, second column 60
  ws['!cols'] = [{ wch: 22 }, { wch: 60 }];

  // Bold the brand row (row 0)
  const brandCell = ws['A1'];
  if (brandCell) {
    brandCell.s = { font: { bold: true, sz: 16 } };
  }

  // Bold label cells in column A (rows 3, 5+, etc.)
  for (const [addr, cell] of Object.entries(ws)) {
    if (addr.match(/^A\d+$/) && cell && typeof cell.v === 'string') {
      const label = cell.v as string;
      if (
        label === companyName ||
        label.startsWith('Report:') ||
        label.startsWith('Description:') ||
        label.startsWith('Plant') ||
        label.startsWith('Filters') ||
        label === 'Generated:' ||
        label === 'Generated By:' ||
        label === 'KPI Summary' ||
        label === 'Metric'
      ) {
        cell.s = { font: { bold: true } };
      }
    }
  }

  XLSX.utils.book_append_sheet(wb, ws, 'Summary');
  return wb;
}

