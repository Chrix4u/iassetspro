/**
 * Add a data sheet to the workbook.
 *
 * - Creates formatted header row from column definitions
 * - Populates rows using column.key to extract values from each row object
 * - Applies number format hints via cell `.z` / `.t` properties
 * - Sets column widths
 * - Optionally freezes header row & adds auto-filter
 * - Optionally stripes alternating rows
 */
export function addDataSheet(
  workbook: XLSX.WorkBook,
  sheetName: string,
  columns: ReportColumn[],
  rows: Record<string, unknown>[],
  options: AddDataSheetOptions = {},
): void {
  const {
    freezeHeader = true,
    freezeColumns = 0,
    autoFilter = true,
    stripeRows = true,
    defaultWidth = 15,
  } = options;

  // Build AOA: header row + data rows
  const aoa: unknown[][] = [];

  // Header row
  aoa.push(columns.map((c) => c.header));

  // Data rows
  for (const row of rows) {
    const dataRow: unknown[] = [];
    for (const col of columns) {
      const raw = row[col.key];
      const formatted = applyCellFormat(raw, col.format);
      dataRow.push(formatted);
    }
    aoa.push(dataRow);
  }

  const ws = XLSX.utils.aoa_to_sheet(aoa);

  // Column widths
  ws['!cols'] = columns.map((c) => ({ wch: c.width || defaultWidth }));

  // Freeze pane — freeze header row (row index 1) + optional left columns
  if (freezeHeader) {
    // XLSX freeze is 0-based: { $freeze$: { x: colCount, y: rowIndex } }
    ws['!freeze'] = { x: freezeColumns, y: 1 };
  }

  // Auto-filter on the header row
  if (autoFilter && columns.length > 0) {
    const range = XLSX.utils.encode_range({
      s: { r: 0, c: 0 },
      e: { r: aoa.length - 1, c: columns.length - 1 },
    });
    ws['!autofilter'] = { ref: range };
  }

  // Apply cell-level styles (numbers, dates, stripe colouring)
  for (let r = 0; r < aoa.length; r++) {
    for (let c = 0; c < columns.length; c++) {
      const cellRef = XLSX.utils.encode_cell({ r, c });
      const cell = ws[cellRef];
      if (!cell) continue;

      const col = columns[c];

      // Number format z-string for Excel
      if (col.format === 'currency') {
        cell.z = '#,##0.00';
        if (typeof cell.v === 'string') {
          const num = Number(cell.v);
          if (!isNaN(num)) { cell.v = num; cell.t = 'n'; }
        }
      } else if (col.format === 'number') {
        cell.z = '#,##0.00';
        if (typeof cell.v === 'string') {
          const num = Number(cell.v);
          if (!isNaN(num)) { cell.v = num; cell.t = 'n'; }
        }
      } else if (col.format === 'percentage') {
        cell.z = '0.0%';
        if (typeof cell.v === 'string') {
          const stripped = (cell.v as string).replace('%', '');
          const num = Number(stripped) / 100;
          if (!isNaN(num)) { cell.v = num; cell.t = 'n'; }
        }
      } else if (col.format === 'date') {
        cell.z = 'yyyy-mm-dd';
      } else if (col.format === 'datetime') {
        cell.z = 'yyyy-mm-dd hh:mm:ss';
      }

      // Header row styling
      if (r === 0) {
        cell.s = {
          font: { bold: true, color: { rgb: 'FFFFFF' } },
          fill: { fgColor: { rgb: '2F5496' } },
          alignment: { horizontal: 'center' },
        };
      } else if (stripeRows && r % 2 === 0) {
        // Alternating row stripe
        cell.s = { fill: { fgColor: { rgb: 'F2F2F2' } } };
      }
    }
  }

  XLSX.utils.book_append_sheet(workbook, ws, sheetName);
}

