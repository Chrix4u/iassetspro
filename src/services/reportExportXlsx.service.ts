/**
 * Add an analytics / supplementary sheet.
 *
 * Accepts an array of row objects where keys become column headers
 * in the first row. Useful for trend data, Pareto tables, KPI
 * breakdowns, etc.
 */
export function addAnalyticsSheet(
  workbook: XLSX.WorkBook,
  sheetName: string,
  rows: AnalyticsRow[],
  options: AddAnalyticsOptions = {},
): void {
  const { autoFilter = true } = options;

  if (rows.length === 0) {
    // Create an empty sheet with a placeholder
    const ws = XLSX.utils.aoa_to_sheet([['No analytics data available']]);
    XLSX.utils.book_append_sheet(workbook, ws, sheetName);
    return;
  }

  // Determine headers from the first row's keys
  const headers = Object.keys(rows[0]);

  // Build AOA
  const aoa: unknown[][] = [headers];
  for (const row of rows) {
    aoa.push(headers.map((h) => row[h] ?? ''));
  }

  const ws = XLSX.utils.aoa_to_sheet(aoa);

  // Column widths
  ws['!cols'] = headers.map((h) => ({ wch: Math.max(h.length + 4, 15) }));

  // Auto-filter
  if (autoFilter && headers.length > 0) {
    const range = XLSX.utils.encode_range({
      s: { r: 0, c: 0 },
      e: { r: aoa.length - 1, c: headers.length - 1 },
    });
    ws['!autofilter'] = { ref: range };
  }

  // Header styling
  for (let c = 0; c < headers.length; c++) {
    const cellRef = XLSX.utils.encode_cell({ r: 0, c });
    const cell = ws[cellRef];
    if (cell) {
      cell.s = {
        font: { bold: true, color: { rgb: 'FFFFFF' } },
        fill: { fgColor: { rgb: '548235' } },
        alignment: { horizontal: 'center' },
      };
    }
  }

  XLSX.utils.book_append_sheet(workbook, ws, sheetName);
}

